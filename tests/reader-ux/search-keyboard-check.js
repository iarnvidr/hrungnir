async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const activeId = () => page.evaluate(() => document.activeElement.closest('[data-thread-id]')?.dataset.threadId);
  const activeComment = () => page.evaluate(() => document.activeElement.closest('.comment')?.dataset.commentId);
  await page.evaluate(() => localStorage.clear());
  await page.setViewportSize({width: 1100, height: 760});
  await page.reload();
  await page.waitForFunction(() => document.querySelectorAll('.thread-item').length === 28);
  const search = page.locator('#cache-search-input');
  await page.keyboard.press('/');
  await page.keyboard.type('hjkl');
  assert(await search.inputValue() === 'hjkl', 'hjkl was intercepted while typing');
  await search.fill('');
  await page.keyboard.press('Escape');
  await page.keyboard.press('j');
  assert(await activeId() === 't3_video', 'j did not move to next post');
  assert(!await page.evaluate(() => window.__ux.calls.some(call => call.command === 'fetch_thread')), 'moving focus fetched a post');
  await page.locator('#flair-filter').selectOption('News');
  await page.locator('.thread-open').first().focus();
  await page.keyboard.press('j');
  assert(await activeId() === 't3_fixture3', 'j ignored the visible flair filter');
  await page.evaluate(() => {
    window.__ux.search.comments = [
      {id: 't1_root', parent_id: 't3_fixture3', body: 'Parent comment'},
      {id: 't1_child', parent_id: 't1_root', body: 'Nested reply'},
      {id: 't1_sibling', parent_id: 't3_fixture3', body: 'Next root comment'},
    ];
  });
  await page.keyboard.press('l');
  await page.waitForFunction(() => window.__ux.posts.has('t3_fixture3'));
  await page.evaluate(() => window.__ux.releasePost('t3_fixture3'));
  await page.waitForFunction(() => document.querySelectorAll('#thread-view .comment').length === 3);
  await page.keyboard.press('j');
  assert(await activeComment() === 't1_root', 'j did not enter comments');
  await page.keyboard.press('l');
  assert(await activeComment() === 't1_child', 'l did not enter child reply');
  await page.keyboard.press('h');
  assert(await activeComment() === 't1_root', 'h did not move to parent');
  await page.keyboard.press('h');
  assert(await page.locator('[data-comment-id="t1_child"]').isHidden(), 'h did not collapse replies');
  await page.keyboard.press('j');
  assert(await activeComment() === 't1_sibling', 'j entered a hidden reply');
  await page.keyboard.press('k');
  await page.keyboard.press('l');
  assert(await page.locator('[data-comment-id="t1_child"]').isVisible(), 'l did not expand replies');
  await page.keyboard.press('h');
  await page.keyboard.press('h');
  assert(await page.locator('#thread-view').evaluate(node => node === document.activeElement), 'h did not return to post root');
  await page.keyboard.press('h');
  assert(await activeId() === 't3_fixture3' && await page.locator('#browse-panel').isVisible(), 'h lost the original listing position/focus');
  await page.keyboard.press('l');
  await page.keyboard.press('j');
  await page.evaluate(() => window.__ux.releasePost('t3_fixture3'));
  await page.waitForFunction(() => !document.querySelector('[data-thread-id="t3_fixture3"]')?.getAttribute('aria-busy') || document.querySelector('[data-thread-id="t3_fixture3"]').getAttribute('aria-busy') === 'false');
  assert(await activeComment() === 't1_root', 'a late redraw lost comment focus');
  assert(await page.locator('[data-comment-id="t1_child"]').isHidden(), 'redraw forgot collapsed replies');
  await page.keyboard.press('Escape');
  await page.locator('#flair-filter').selectOption('');
  const fetch = async name => {
    await page.locator('#subreddit-input').fill(name);
    await page.locator('#browse-submit').click();
    await page.waitForFunction(() => !document.querySelector('#browse-submit').disabled);
  };
  await fetch('soccer');
  await fetch('space');
  await page.locator('.thread-open').first().focus();
  await page.keyboard.press('h');
  assert(await page.evaluate(() => document.activeElement.dataset.subreddit) === 'space', 'h did not focus current community');
  await page.keyboard.press('j');
  assert(await page.evaluate(() => document.activeElement.dataset.subreddit) === 'soccer', 'j did not navigate communities');
  await page.keyboard.press('l');
  await page.waitForFunction(() => document.activeElement.matches('.thread-open'));
  assert((await page.locator('#current-subreddit').innerText()).includes('soccer'), 'l did not open selected community');
  await page.keyboard.press('h');
  await page.keyboard.press('j');
  const communityCalls = await page.evaluate(() => window.__ux.calls.filter(call => call.command === 'fetch_subreddit').length);
  await page.evaluate(() => { window.__ux.search.holdCommunity = true; });
  await page.keyboard.down('l');
  await page.keyboard.down('l');
  await page.keyboard.up('l');
  await page.waitForFunction(() => typeof window.__ux.search.releaseCommunity === 'function');
  assert(await page.evaluate(() => window.__ux.calls.filter(call => call.command === 'fetch_subreddit').length) === communityCalls + 1, 'held l queued duplicate community fetches');
  await page.keyboard.press('/');
  await search.fill('a new draft');
  await page.evaluate(() => { window.__ux.search.holdCommunity = false; window.__ux.search.releaseCommunity(); });
  await page.waitForFunction(() => !document.querySelector('#browse-submit').disabled);
  assert(await search.evaluate(node => document.activeElement === node), 'late community fetch stole focus from typing');
  await search.fill('');
  await page.keyboard.press('Escape');
  await fetch('soccer');

  await page.evaluate(() => { window.__ux.search.rows = window.__ux.threads.slice(0, 2); });
  await page.keyboard.press('/');
  await search.fill('gangs of london s02e08');
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelectorAll('.thread-item').length === 2 && !document.querySelector('#browse-submit').disabled);
  assert(await activeId() === 't3_article', 'search did not focus its results');
  assert(await page.evaluate(() => window.__ux.calls.filter(call => call.command === 'search_reddit').at(-1).args.smart === true), 'episode matching not enabled');
  await page.keyboard.press('j');
  assert(await activeId() === 't3_video', 'j navigated the underlying subreddit instead of search results');
  await page.keyboard.press('l');
  assert((await page.locator('#thread-view h1').innerText()).includes('Match highlights'), 'l opened the wrong search result');
  await page.keyboard.press('h');
  await page.locator('.search-options summary').click();
  await page.locator('#search-smart').uncheck();
  await page.waitForFunction(() => !document.querySelector('#header-search-submit').disabled);
  assert(await page.evaluate(() => window.__ux.calls.filter(call => call.command === 'search_reddit').at(-1).args.smart === false), 'as-typed search option was ignored');
  await page.locator('#search-scope').selectOption('subreddit');
  await page.waitForFunction(() => document.querySelectorAll('.thread-item').length === 1 && !document.querySelector('#header-search-submit').disabled);
  assert(await page.evaluate(() => window.__ux.calls.filter(call => call.command === 'search_reddit').at(-1).args.subreddit === 'soccer'), 'community scope was not sent');
  assert((await page.locator('#current-subreddit').innerText()).includes('r/soccer'), 'community scope is invisible');
  await search.focus();
  await page.keyboard.press('Escape');
  assert(await search.inputValue() === 'gangs of london s02e08', 'Escape discarded the search');

  const remoteBefore = await page.evaluate(() => window.__ux.calls.filter(call => call.command === 'search_reddit').length);
  await page.evaluate(() => {
    window.__ux.search.hits = [{id: 't3_discussion', title: 'Downloaded episode discussion', subreddit: 'space', snippet: 'An offline comment match', comment_id: 't1_parent'}];
  });
  await page.locator('#search-scope').selectOption('cache');
  await page.waitForFunction(() => document.querySelectorAll('#thread-list .cache-search-hit').length === 1);
  assert(await page.evaluate(() => window.__ux.calls.filter(call => call.command === 'search_reddit').length) === remoteBefore, 'downloaded search contacted Reddit');
  assert((await page.locator('#thread-list').innerText()).includes('offline comment'), 'downloaded snippets missing');
  await page.locator('#thread-list .cache-search-hit').focus();
  await page.keyboard.press('l');
  await page.waitForFunction(() => document.querySelector('#reader-panel').hidden === false && document.activeElement.dataset.commentId === 't1_parent');
  await page.keyboard.press('Escape');
  await page.keyboard.press('?');
  assert(await page.locator('#keyboard-help-dialog').isVisible(), 'keyboard help is unavailable');
  await page.keyboard.press('j');
  assert(await page.locator('#keyboard-help-dialog').isVisible(), 'shortcuts escaped a dialog');
  await page.keyboard.press('Escape');
  await page.evaluate(() => { window.__ux.search.rows = []; });
  await page.locator('#search-scope').selectOption('all');
  await page.waitForFunction(() => !document.querySelector('#empty-state').hidden && !document.querySelector('#header-search-submit').disabled);
  assert((await page.locator('#thread-count').innerText()).includes('0 posts'), 'empty search kept old results');
  await page.evaluate(() => { window.__ux.search.error = true; });
  await search.focus();
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('#reader-feedback').textContent.includes('Search source unavailable'));
  await page.evaluate(() => { window.__ux.search.error = false; window.__ux.search.rows = window.__ux.threads.slice(0, 2); });
  await page.locator('#reader-feedback .retry-action').click();
  await page.waitForFunction(() => document.querySelectorAll('.thread-item').length === 2 && !document.querySelector('#header-search-submit').disabled);
  await page.setViewportSize({width: 500, height: 800});
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'search controls overflow narrow window');
  await page.locator('.search-options summary').click();
  const options = await page.locator('.search-options > div').boundingBox();
  assert(options.x >= 0 && options.x + options.width <= 500, 'search options extend outside the window');
  await page.locator('.search-options summary').click();
  await page.screenshot({path: '/tmp/hrungnir-search-keyboard.png'});
  return {passed: ['typing safety', 'focus without fetch', 'flair-filtered navigation', 'comment tree hjkl', 'redraw preserves comment state', 'subreddit hjkl', 'search-result navigation', 'search scopes and match modes', 'downloaded comment search without network', 'Escape preserves query', 'shortcut help', 'empty/error/retry states', 'narrow search layout']};
}
